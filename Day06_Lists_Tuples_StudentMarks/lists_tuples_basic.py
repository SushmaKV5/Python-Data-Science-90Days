#List example(Mutable Datatype) 

subjects = ["Maths", "Science", "English", "Computer"]
marks = [89,74,95,98]

print("Subjects:", subjects)
print("Marks:", marks)

#Accesing a single elements in lists
print("\nFirst subject is:", subjects[0])
print("First subject's marks:", marks[0])

#Updating elements in lists
marks[1] = 85
print("\nUpdated marks:", marks)

#Tuple example (Immutable Datatype)
student_info = ("Sushma", 21, "Data science")

print("\nStudent info(tuple)")
print(student_info)